def akey(r: dict | None) -> str | None:
    """Attack key of a row: attack.type, plus @boost when a non-default boost is set ("scale@3")."""
    if not r:
        return None
    b = _num(rget(r, "attack.boost"))
    t = rget(r, "attack.type") or "none"
    return f"{t}@{b:g}" if b else t


def pick_att(rows: list[dict], att: str, **kw) -> dict | None:
    for r in rows:
        if akey(r) == att and all(rget(r, k.replace("__", ".")) == v for k, v in kw.items()):
            return r
    return None


# ------------------------------------------------------------------ helpers

def _num(v: Any) -> float | None:
    try:
        f = float(v)
        return None if math.isnan(f) else f
    except (TypeError, ValueError):
        return None


def _nan(v: Any) -> float:
    f = _num(v)
    return np.nan if f is None else f


def fmt(v: Any, d: int = 3) -> str:
    f = _num(v)
    return "--" if f is None else f"{f:.{d}f}"


def fmt_ci(r: dict | None, m: str, d: int = 3) -> str:
    if not r or _num(r.get(m)) is None:
        return "--"
    lo, hi = _num(r.get(f"{m}_lo")), _num(r.get(f"{m}_hi"))
    if lo is None or hi is None:
        return fmt(r[m], d)
    return f"{r[m]:.{d}f}\\,{{\\scriptsize[{lo:.{d}f},{hi:.{d}f}]}}"


def rget(r: dict, key: str) -> Any:
    """Value of a configuration key for an analysis row; keys that do not vary in the grid are not columns of
    the row, so fall back to the overrides / resolved configuration of the row's first job."""
    if key in r:
        return r[key]
    js = r.get("_jobs") or []
    if js:
        res = js[0].get("res", {})
        ov = res.get("overrides", {})
        if key in ov:
            return ov[key]
        if key == "train.peft":
            return (res.get("effective") or {}).get(key, "head")
    return None


def pick(rows: list[dict], **kw) -> dict | None:
    for r in rows:
        if all(rget(r, k.replace("__", ".")) == v for k, v in kw.items()):
            return r
    return None


def _tabular(cols: str, header: list[str], body: list[list[str]], caption: str, label: str,
             groups: list[tuple[int, str]] | None = None) -> str:
    lines = ["% generated by `burstguard paper` - do not edit by hand", "\\begin{table}[t]", "\\centering",
             "\\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}", f"\\begin{{tabular}}{{{cols}}}",
             "\\toprule"]
    if groups:
        lines.append(" & ".join(f"\\multicolumn{{{n}}}{{c}}{{{t}}}" if n > 1 else t for n, t in groups) + " \\\\")
        c0 = 1
        rules = []
        for n, t in groups:
            if t and n > 1:
                rules.append(f"\\cmidrule(lr){{{c0}-{c0 + n - 1}}}")
            c0 += n
        lines.append(" ".join(rules))
    lines.append(" & ".join(header) + " \\\\")
    lines.append("\\midrule")
    for row in body:
        lines.append("\\midrule" if row == ["--midrule--"] else " & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def _load(root: Path, name: str, split: str = "test", log=print) -> tuple[list[dict], list[str]] | None:
    gdir = root / name
    if not gdir.exists():
        return None
    try:
        rows, varying, _ = AN.build_rows(gdir, split, log=lambda *a: None)
        return rows, varying
    except RuntimeError:
        return None


def _plt():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "axes.titlesize": 8, "axes.labelsize": 8, "legend.fontsize": 6.5,
                         "figure.dpi": 150, "savefig.bbox": "tight"})
    return plt


def _save(fig, fdir: Path, name: str, made: list[str]) -> None:
    for ext in ("pdf", "png"):
        fig.savefig(fdir / f"{name}.{ext}")
    made.append(f"figures/{name}.pdf")


