def fig_scores(root: Path, fdir: Path, made: list[str], numbers: dict) -> None:
    """Score margins (v0.3.10): per-round BurstGuard scores of clean rounds and of the units that contain a malicious
    update (E3; plain poisoning from X7), against the default threshold floors and (X8) the calibrated thresholds.
    All ROC AUCs are 1.0, so the margin between the two populations is the informative quantity."""
    t = _load(root, "E3_defenses")
    if not t:
        return
    rows = t[0]
    t7 = _load(root, "X7_poison_defenses")
    rows7 = t7[0] if t7 else []
