def table_dataset(ds_path: Path, tdir: Path, numbers: dict) -> str | None:
    from burstguard.data.store import describe, load_dataset
    if not ds_path.exists():
        return None
    ds = load_dataset(ds_path)
    d = describe(ds)
    t0 = _dt.date(2013, 11, 1)
    body = []
    for sp in ("train", "val", "test", "holiday"):
        a, b = d["bounds"][sp]
        da, db = t0 + _dt.timedelta(days=a // 144), t0 + _dt.timedelta(days=(b - 1) // 144)
        body.append([sp.capitalize(), f"{da:%d %b} -- {db:%d %b %Y}", f"{(b - a) // 144}", f"{b - a}"])
    means = np.array([r["mean"] for r in d["per_site"]])
    cv = np.array([r["std_train"] / max(r["mean"], 1e-9) for r in d["per_site"]])
    numbers["dataset"] = {"sites": d["num_sites"], "probe_blocks": d.get("num_probe"), "slots": d["T"],
                          "site_mean_min": float(means.min()), "site_mean_median": float(np.median(means)),
                          "site_mean_max": float(means.max()), "site_cv_median": float(np.median(cv))}
    cap = (f"Milan Internet activity (Telecom Italia, 10-minute slots): {d['num_sites']} sites (5$\\times$5-cell "
           f"blocks), {d.get('num_probe')} public probe blocks held by the server. Mean activity per site ranges "
           f"{means.min():.0f}--{means.max():.0f} (median {np.median(means):.0f}); median coefficient of variation "
           f"{np.median(cv):.2f}.")
    (tdir / "dataset.tex").write_text(_tabular("lrrr", ["Split", "Period", "Days", "Slots"], body, cap,
                                               "tab:dataset"))
    return "tables/dataset.tex"


def table_clean(root: Path, tdir: Path, numbers: dict) -> str | None:
    t = _load(root, "E1_clean")
    if not t:
        return None
    rows, _ = t
    hol = _load(root, "E1_clean", "holiday")
    hrows = hol[0] if hol else []
    body = []
    zs = pick(rows, job__kind="zeroshot")
    if zs:
        hz = pick(hrows, job__kind="zeroshot")
        body.append([KIND_TEX["zeroshot"], "--", fmt_ci(zs, "mase_daily"), fmt_ci(hz, "mase_daily"),
                     fmt(zs.get("smape"), 1), "--", "--"])
        body.append(["--midrule--"])
    numbers["clean"] = {}
    for kind in ("local_only", "centralized", "fl"):
        for peft in PEFTS:
            r = pick(rows, job__kind=kind, train__peft=peft)
            if not r:
                continue
            h = pick(hrows, job__kind=kind, train__peft=peft)
            kib = _num(r.get("update_bytes"))
            body.append([KIND_TEX[kind], PEFT_TEX[peft], fmt_ci(r, "mase_daily"), fmt_ci(h, "mase_daily"),
                         fmt(r.get("smape"), 1), fmt(kib / 1024, 0) if kib and kind == "fl" else "--",
                         fmt(r.get("client_train_cpu_s_mean"), 1) if kind == "fl" else "--"])
            numbers["clean"][f"{kind}/{peft}"] = {"mase_test": _num(r.get("mase_daily")),
                                                 "mase_holiday": _num((h or {}).get("mase_daily")),
                                                 "kib_update": kib / 1024 if kib else None}
        body.append(["--midrule--"])
    if body and body[-1] == ["--midrule--"]:
        body.pop()
    if zs:
        numbers["clean"]["zeroshot"] = {"mase_test": _num(zs.get("mase_daily"))}
    cap = ("Clean forecasting accuracy (6-hour horizon) of TTM-R2 on the 20 Milan sites: MASE w.r.t. the daily "
           "seasonal-naive forecast (lower is better), mean [95\\% CI] over seeds$\\times$sites; KiB = size of one "
           "client update; CPU = local training seconds per client and round.")
    (tdir / "clean.tex").write_text(_tabular("llrrrrr", ["Setting", "Tuned", "MASE test", "MASE holiday", "sMAPE",
                                                         "KiB", "CPU s"], body, cap, "tab:clean"))
    return "tables/clean.tex"


def table_vulnerability(root: Path, tdir: Path, numbers: dict) -> str | None:
    t = _load(root, "E2_attacks")
    if not t:
        return None
    rows, _ = t
    e1 = _load(root, "E1_clean")       # since v0.3.4 E2 has no clean runs: the clean reference is E1 (FL, FedAvg)
    e1_rows = e1[0] if e1 else []
    body = []
    numbers["vulnerability"] = {}
    for peft in PEFTS:
        clean = pick(rows, attack__type="none", train__peft=peft) or next(
            (r for r in e1_rows if (rget(r, "job.kind") or "fl") == "fl" and rget(r, "train.peft") == peft), None)
        cells_peft = [(att, pick_att(rows, att, train__peft=peft)) for att in ATTACKS]
        cells_peft = [(a, r) for a, r in cells_peft if r]
        if not cells_peft:
            continue
        if body:
            body.append(["--midrule--"])
        body.append([PEFT_TEX[peft], "No attack", "--", fmt_ci(clean, "upr_trig", 2) if clean else "--",
                     fmt_ci(clean, "mase_daily") if clean else "--", "--"])
        for att, r in cells_peft:
            d = None
            if clean and _num(r.get("mase_daily")) and _num(clean.get("mase_daily")):
                d = 100 * (r["mase_daily"] / clean["mase_daily"] - 1)
            body.append(["", ATTACK_TEX.get(att, att), fmt_ci(r, "asr", 2), fmt_ci(r, "upr_trig", 2),
                         fmt_ci(r, "mase_daily"), "--" if d is None else f"{d:+.1f}"])
            numbers["vulnerability"][f"{peft}/{att}"] = {"asr": _num(r.get("asr")), "upr_trig": _num(r.get("upr_trig")),
                                                         "mase": _num(r.get("mase_daily")), "dmase_pct": d}
    cap = ("Vulnerability of federated fine-tuning to burst-triggered backdoors (2 of 20 sites malicious, FedAvg): "
           "attack success rate on triggered test windows of benign sites (ASR, forecast within 50\\% of the "
           "attacker's target), under-provisioning rate on triggered windows (UPR$_{trig}$, forecast below 80\\% of "
           "the truth), clean MASE and its relative change against the clean federation ($\\Delta$\\%). "
           "$\\gamma$ = update boost of the malicious sites ($\\gamma$=1: plain poisoning, $\\gamma$=10 = $n/m$: "
           "model replacement).")
    hdr = ["Tuned", "Attack", "ASR", "UPR$_{trig}$", "MASE", "$\\Delta$MASE\\%"]
    (tdir / "vulnerability.tex").write_text(_tabular("llrrrr", hdr, body, cap, "tab:vulnerability"))
    return "tables/vulnerability.tex"


def table_defenses(root: Path, tdir: Path, numbers: dict) -> str | None:
    t = _load(root, "E3_defenses")
    if not t:
        return None
    rows, _ = t
    t7 = _load(root, "X7_poison_defenses")     # v0.3.10: plain data poisoning against the same defenses
    rows7 = t7[0] if t7 else []
    atts = [(a, rows) for a in ATTACKS_E3] + ([("poison", rows7)] if rows7 else [])
    t8 = _load(root, "X8_bg_calibrated")        # v0.3.11: calibrated BurstGuard (extra row)
    rows8 = t8[0] if t8 else []
    made = None
    numbers["defenses"] = {}
    for peft in ("head", "lora"):
        body = []
        for d in DEFENSE_ORDER:
            clean = pick(rows, attack__type="none", defense__name=d, train__peft=peft)
            if not clean and not pick(rows, defense__name=d, train__peft=peft):
                continue
            fpr = clean.get("fpr_units") if clean else None
            # SecAgg column (works on the securely aggregated model alone) and UPR_trig instead of the strict ASR,
            # which stays near 0 for the covert attacker although it under-forecasts most triggered windows
            sec = "yes" if d in SECAGG_OK else ("no$^\\dagger$" if d == "clip_noise" else "no")
            cells = [DEFENSE_TEX.get(d, d), sec, fmt(clean.get("mase_daily") if clean else None),
                     fmt(fpr, 2) if d in ("burstguard", "probe_screen") else "--"]
            for att, src in atts:
                r = pick_att(src, att, defense__name=d, train__peft=peft)
                cells += [fmt((r or {}).get("upr_trig"), 2), fmt((r or {}).get("mase_daily"))]
                numbers["defenses"][f"{peft}/{d}/{att}"] = {"asr": _num((r or {}).get("asr")),
                                                            "upr_trig": _num((r or {}).get("upr_trig")),
                                                            "mase": _num((r or {}).get("mase_daily")),
                                                            "tpr_units": _num((r or {}).get("tpr_units"))}
            numbers["defenses"][f"{peft}/{d}/none"] = {"mase": _num((clean or {}).get("mase_daily")),
                                                       "fpr_units": _num(fpr),
                                                       "upr_trig": _num((clean or {}).get("upr_trig"))}
            body.append(cells)
        if rows8:   # v0.3.11: BurstGuard with the per-deployment calibration (X8; clean runs on held-out seeds)
            clean = pick_att(rows8, "none", train__peft=peft)
            if clean or pick(rows8, train__peft=peft):
                fpr = (clean or {}).get("fpr_units")
                cells = ["\\textbf{BurstGuard} (cal.)", "yes", fmt((clean or {}).get("mase_daily")), fmt(fpr, 2)]
                for att, _ in atts:
                    r = pick_att(rows8, att, train__peft=peft)
                    cells += [fmt((r or {}).get("upr_trig"), 2), fmt((r or {}).get("mase_daily"))]
                    numbers["defenses"][f"{peft}/burstguard_cal/{att}"] = {
                        "asr": _num((r or {}).get("asr")), "upr_trig": _num((r or {}).get("upr_trig")),
                        "mase": _num((r or {}).get("mase_daily")), "tpr_units": _num((r or {}).get("tpr_units"))}
                numbers["defenses"][f"{peft}/burstguard_cal/none"] = {
                    "mase": _num((clean or {}).get("mase_daily")), "fpr_units": _num(fpr),
                    "upr_trig": _num((clean or {}).get("upr_trig"))}
                body.append(cells)
        if not body:
            continue
        cap = (f"Defenses against burst-triggered backdoors ({PEFT_TEX[peft]} fine-tuning, 2/20 malicious sites). "
               "SecAgg: the defense needs only the (securely) aggregated model, not individual updates "
               "($^\\dagger$norm clipping at the server needs the individual update norms; under secure aggregation "
               "the clients would clip themselves and a malicious client can skip it). Clean MASE without attack, "
               "false-positive rate on clean rounds (FPR), and UPR$_{trig}$ (share of triggered windows forecast "
               "below 80\\% of the truth; about 0.01 without attack) / MASE under each attack (means over "
               "seeds$\\times$sites; CIs and the strict ASR in the CSV of experiments E3"
               + (" and X7" if rows7 else "") + ")."
               + (" BurstGuard uses the default thresholds of the pilot (0.08 / 0.3, adaptive anchor); BurstGuard "
                  "(cal.) the per-deployment calibration on clean rounds (1.5$\\times$ the largest clean score, fixed "
                  "anchor; X8, its clean MASE and FPR on seeds not used for calibration)." if rows8 else ""))
        groups = [(4, "")] + [(2, ATTACK_TEX[a]) for a, _ in atts]
        hdr = ["Defense", "SecAgg", "Clean MASE", "FPR"] + ["UPR", "MASE"] * len(atts)
        (tdir / f"defenses_{peft}.tex").write_text(_tabular("lcrr" + "rr" * len(atts), hdr, body, cap,
                                                            f"tab:defenses-{peft}", groups))
        made = f"tables/defenses_{peft}.tex"
    return made and "tables/defenses_head.tex, tables/defenses_lora.tex"


def _variant_label(r: dict, varying: list[str]) -> str:
    parts = [f"{k.split('.')[-1]}={r.get(k)}" for k in varying
             if k.startswith("burstguard.") and k != "burstguard.mode" and r.get(k) is not None
             and not (k == "burstguard.restarts" and r.get("burstguard.steps") == 0)]
    return ", ".join(parts) or "default (both refs, K=8, R=1, 32 probes, W=6, 2$\\sigma$)"


def table_ablation(root: Path, tdir: Path, numbers: dict) -> str | None:
    t = _load(root, "E9_ablation")
    if not t:
        return None
    rows, varying = t
    others = [k for k in varying if not k.startswith("attack.")]
    variants: dict[str, dict[str, dict]] = {}
    for r in rows:
        key = json.dumps({k: r.get(k) for k in others}, sort_keys=True)
        variants.setdefault(key, {})[akey(r)] = r
    body = []
    numbers["ablation"] = {}
    for key, by_att in sorted(variants.items(), key=lambda kv: (kv[0] != json.dumps({k: None for k in others},
                                                                                      sort_keys=True), kv[0])):
        any_r = next(iter(by_att.values()))
        lab = _variant_label(any_r, varying)
        sc, cs, cl = by_att.get("scale"), by_att.get("scale@3"), by_att.get("none")
        body.append([lab.replace("_", "\\_"), fmt((sc or {}).get("auc_vs_clean"), 3),
                     fmt((cs or {}).get("auc_vs_clean"), 3), fmt((sc or {}).get("tpr_units"), 2),
                     fmt((cs or {}).get("tpr_units"), 2), fmt((cl or {}).get("fpr_units"), 2),
                     fmt((cl or {}).get("screen_cpu_s_mean"), 1)])
        numbers["ablation"][lab] = {"auc_scale": _num((sc or {}).get("auc_vs_clean")),
                                    "auc_covert": _num((cs or {}).get("auc_vs_clean")),
                                    "fpr_clean": _num((cl or {}).get("fpr_units")),
                                    "screen_cpu_s": _num((cl or {}).get("screen_cpu_s_mean"))}
        if key == json.dumps({k: None for k in others}, sort_keys=True):
            # decision-rule variants replayed on the default variant's monitor-mode rounds (no extra runs)
            for rule, rl in (("last", "reference = last only"), ("anchor", "reference = anchor only"),
                             ("fixed_anchor", "fixed anchor threshold")):
                g = lambda r, m: (r or {}).get(f"rule_{rule}_{m}")  # noqa: E731
                if all(g(r, "tpr_units") is None for r in (sc, cs)):
                    continue
                body.append([f"{rl} (replayed)", fmt(g(sc, "auc_vs_clean"), 3), fmt(g(cs, "auc_vs_clean"), 3),
                             fmt(g(sc, "tpr_units"), 2), fmt(g(cs, "tpr_units"), 2),
                             fmt(g(sc, "fpr_clean") if g(sc, "fpr_clean") is not None else g(cl, "fpr_units"), 2),
                             "--"])
                numbers["ablation"][f"rule:{rule}"] = {"auc_scale": _num(g(sc, "auc_vs_clean")),
                                                       "auc_covert": _num(g(cs, "auc_vs_clean")),
                                                       "tpr_scale": _num(g(sc, "tpr_units")),
                                                       "tpr_covert": _num(g(cs, "tpr_units")),
                                                       "fpr_clean": _num(g(sc, "fpr_clean"))}
    cap = ("BurstGuard ablation (Head fine-tuning, monitor mode): ROC AUC of the per-round score separating attacked "
           "rounds from clean-federation rounds, detection rate (TPR) at the deployed thresholds, false-positive "
           "rate on clean rounds, and server CPU seconds per screened round. Rows marked replayed apply another "
           "decision rule to the scores of the default variant (same rounds; AUC of the single score).")
    hdr = ["Variant", "AUC $\\gamma$=10", "AUC $\\gamma$=3", "TPR $\\gamma$=10", "TPR $\\gamma$=3", "FPR", "CPU s"]
    (tdir / "ablation.tex").write_text(_tabular("lrrrrrr", hdr, body, cap, "tab:ablation"))
    return "tables/ablation.tex"


